#!/usr/bin/env node
// Writes docs/ZOHO_FIELDS.md from the field catalogue (src/zoho/fieldCatalog.js),
// using the API names currently configured in .env.
//
//   npm run docs:fields

const fs = require('node:fs');
const path = require('node:path');
const config = require('../src/config');
const { fieldCatalog } = require('../src/zoho/fieldCatalog');

const catalog = fieldCatalog(config);
const toCreate = catalog.flatMap((m) => m.fields.filter((f) => !f.standard).map((f) => ({ ...f, module: m.label })));
const cell = (text) => String(text).replace(/\|/g, '\\|');

const lines = [
  '# Zoho CRM fields used by the Client Portal',
  '',
  '> Generated by `npm run docs:fields` from `src/zoho/fieldCatalog.js`. Do not edit by hand.',
  '> The same list, with a live found/missing check against your org, is in the admin console under **Zoho setup**.',
  '',
  'API names below are the defaults. If your org already uses different names, keep your fields and set the matching',
  '`CRM_*` variable in `.env` (see `src/config.js`).',
  '',
  '## Checklist: what to create in Zoho',
  '',
  `1. **Custom module \`${config.crm.propertiesModule}\`** with the fields marked *Create* below.`,
  ...toCreate.filter((f) => f.module !== 'Properties').map((f, i) => `${i + 2}. **${f.module}: \`${f.apiName}\`** (${f.label}, ${f.type}).`),
  `${toCreate.filter((f) => f.module !== 'Properties').length + 2}. **Leads: Lead Source picklist value \`${config.crm.referral.leadSource}\`**.`,
  `${toCreate.filter((f) => f.module !== 'Properties').length + 3}. **${config.crm.propertiesModule}: Status picklist value \`${config.crm.availableStatus}\`** for listings clients may see.`,
  '',
  `Everything else is a standard Zoho field. In total: ${catalog.reduce((n, m) => n + m.fields.length, 0)} fields across ${catalog.length} modules, ${toCreate.length} to create.`,
  '',
];

for (const module of catalog) {
  lines.push(`## ${module.label} (\`${module.module}\`): ${module.kind}`, '', module.purpose, '');
  if (!module.fields.length) continue;
  lines.push('| Field label | API name | Type | Required | Create? | Used for |', '|---|---|---|---|---|---|');
  for (const f of module.fields) {
    lines.push(`| ${cell(f.label)} | \`${f.apiName}\` | ${cell(f.type)} | ${f.required ? 'Yes' : 'Optional'} | ${f.standard ? 'Standard' : '**Create**'} | ${cell(f.purpose)} |`);
  }
  lines.push('');
}

lines.push(
  '## OAuth scopes',
  '',
  '`ZohoCRM.modules.ALL, ZohoCRM.coql.READ, ZohoCRM.settings.fields.READ, ZohoCRM.users.READ`',
  '',
  'For least privilege, narrow `modules.ALL` to: read on Contacts, Deals and Properties; create on Notes, Tasks and Leads; read on Leads.',
  '',
);

const out = path.join(__dirname, '..', 'docs', 'ZOHO_FIELDS.md');
fs.writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${path.relative(process.cwd(), out)}`);
