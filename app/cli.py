async def create_user(args: argparse.Namespace) -> None:
    settings = load_settings()
    password = args.password or getpass.getpass("Password (at least 10 characters): ")
    problem = password_problem(password, args.email)
    if problem:
        sys.exit(problem)
    db = Database(settings.database_url)
    await db.create_all()
    users = UserStore(db)
    if await users.by_email(args.email):
        sys.exit("That email already has an account.")
    if args.role == "admin":
        if not args.name:
            sys.exit("Give the admin a --name.")
        user = await users.create(email=args.email, password=password, role="admin", name=args.name, email_verified=False)
        print(f"Admin account ready: {user.email} ({user.name}). They confirm their email with a code at first sign-in.")
    else:
        crm = create_crm(settings)
        contact = await crm.find_contact_by_email(args.email)
        if not contact:
            sys.exit(f"No Zoho Contact found for {args.email}.")
        won, lost = settings.crm.won_stages, settings.crm.lost_stages
        if not any(d["stage"] not in won and d["stage"] not in lost for d in await crm.list_deals(contact["id"])):
            sys.exit(f"{contact['name']} has no active deal in Zoho; client access needs one.")
        user = await users.create(email=args.email, password=password, role="client", name=contact["name"], contact_id=contact["id"],
                                  must_change_password=True)
        print(f"Client access granted: {user.email} -> Zoho Contact {contact['id']} ({contact['name']}).")
    await db.dispose()


async def mcp_check(args: argparse.Namespace) -> None:
    from .mcp_zoho.connection import McpConnection
    from .mcp_zoho.zoho_mcp_api import ZohoMcpApi, load_tool_map

    settings = load_settings()
    if not settings.zoho_mcp.url:
        sys.exit("Set ZOHO_MCP_URL in .env first (Zoho CRM > Setup > Developer Hub > MCP for AI Agents).")
    headers = {"Authorization": settings.zoho_mcp.authorization} if settings.zoho_mcp.authorization else {}
    connection = McpConnection(settings.zoho_mcp.url, headers=headers)
    try:
        tools = await connection.list_tools()
        print(f"Connected. The server offers {len(tools)} tools:\n")
        for tool in tools:
            print(f"- {tool.name}: {(tool.description or '').splitlines()[0][:100] if tool.description else ''}")
            if args.schemas:
                import json
                print("    " + json.dumps(tool.input_schema if hasattr(tool, "input_schema") else tool.inputSchema, indent=2).replace("\n", "\n    "))
        tool_map = load_tool_map(settings.zoho_mcp.tool_map_path)
        names = {t.name for t in tools}
        print(f"\nMapping in {settings.zoho_mcp.tool_map_path}:")
        for op, entry in tool_map.items():
            found = entry["tool"] in names
            print(f"  {'OK     ' if found else 'MISSING'} {op} -> {entry['tool']}")
            if op == "coql" and not found:
                sys.exit('The required "coql" tool was not found. Edit the mapping file with the right tool name and arguments.')
        api = ZohoMcpApi(connection=connection, tool_map=tool_map, crm=settings.crm)
        d = settings.crm.deal
        rows = await api.coql(f"select {d.name}, {d.stage} from {settings.crm.deals_module} where {d.stage} is not null limit 1")
        print(f"\nTest COQL query returned {len(rows)} deal row(s). The AI can read Zoho CRM over MCP.")
    finally:
        await connection.close()


def field_docs(_: argparse.Namespace) -> None:
    settings = load_settings()
    catalog = field_catalog(settings)
    to_create = [(m["label"], f) for m in catalog for f in m["fields"] if not f["standard"]]
    other = [(label, f) for label, f in to_create if label != "Properties"]
    cell = lambda t: str(t).replace("|", "\\|")  # noqa: E731
    lines = [
        "# Zoho CRM fields used by the Client Portal", "",
        "> Generated by `python -m app.cli field-docs` from `app/zoho/field_catalog.py`. Do not edit by hand.",
        "> The same list, with a live found/missing check against your org, is in the admin console under **Zoho setup**.", "",
        "API names below are the defaults. If your org already uses different names, keep your fields and set the matching",
        "`CRM_*` variable in `.env` (see `app/config.py`).", "",
        "## Checklist: what to create in Zoho", "",
        f"1. **Custom module `{settings.crm.properties_module}`** with the fields marked *Create* below.",
        *[f"{i + 2}. **{label}: `{f['apiName']}`** ({f['label']}, {f['type']})." for i, (label, f) in enumerate(other)],
        f"{len(other) + 2}. **Leads: Lead Source picklist values `{settings.crm.signup.lead_source}` and `{settings.crm.referral.lead_source}`**.",
        f"{len(other) + 3}. **{settings.crm.properties_module}: Status picklist value `{settings.crm.available_status}`** for listings clients may see.", "",
        f"Everything else is a standard Zoho field. In total: {sum(len(m['fields']) for m in catalog)} fields across {len(catalog)} modules, {len(to_create)} to create.", "",
    ]
    for m in catalog:
        lines += [f"## {m['label']} (`{m['module']}`): {m['kind']}", "", m["purpose"], ""]
        if m["fields"]:
            lines += ["| Field label | API name | Type | Required | Create? | Used for |", "|---|---|---|---|---|---|"]
            lines += [f"| {cell(f['label'])} | `{f['apiName']}` | {cell(f['type'])} | {'Yes' if f['required'] else 'Optional'} | "
                      f"{'Standard' if f['standard'] else '**Create**'} | {cell(f['purpose'])} |" for f in m["fields"]]
            lines.append("")
    lines += ["## OAuth scopes", "", "`ZohoCRM.modules.ALL, ZohoCRM.coql.READ, ZohoCRM.settings.fields.READ, ZohoCRM.users.READ`", "",
              "For least privilege, narrow `modules.ALL` to: read on Contacts, Deals and Properties; create and update on Leads; create on Notes and Tasks.", ""]
    out = ROOT / "docs" / "ZOHO_FIELDS.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"Wrote {out.relative_to(ROOT)}")


def schema_sql(_: argparse.Namespace) -> None:
    """PostgreSQL / Supabase DDL: the private schema, tables, indexes, column
    comments (each naming its Zoho source) and the Supabase lockdown."""
    dialect = postgresql.dialect()
    q = lambda text: text.replace("'", "''")  # noqa: E731
    parts = [
        "-- Client Portal database schema for PostgreSQL 16+ / Supabase.",
        "-- Generated by `python -m app.cli schema-sql` from app/db.py; the app also creates these on first start.",
        "-- Diagram and data dictionary: docs/DATA_MODEL.md", "",
        f"CREATE SCHEMA IF NOT EXISTS {SCHEMA};", "",
    ]
    for table in Base.metadata.sorted_tables:
        parts.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";\n")
        for index in sorted(table.indexes, key=lambda i: i.name):
            parts.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";")
        if table.comment or (table.name in DESCRIPTIONS):
            parts.append(f"COMMENT ON TABLE {SCHEMA}.{table.name} IS '{q(DESCRIPTIONS.get(table.name, table.comment or ''))}';")
        for column in table.columns:
            if column.comment:
                parts.append(f"COMMENT ON COLUMN {SCHEMA}.{table.name}.{column.name} IS '{q(column.comment)}';")
        parts.append("")
    parts += [
        "-- ---------------------------------------------------------------------------",
        "-- Supabase lockdown: the portal talks to PostgreSQL directly and does not use",
        "-- Supabase's Data API, Auth or Storage. Keep these tables unreachable from it.",
        "-- (Also switch the Data API off, or leave `portal` out of its exposed schemas.)",
        "-- ---------------------------------------------------------------------------",
        "DO $$ BEGIN",
        "  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN",
        f"    REVOKE ALL ON SCHEMA {SCHEMA} FROM anon, authenticated;",
        f"    REVOKE ALL ON ALL TABLES IN SCHEMA {SCHEMA} FROM anon, authenticated;",
        "  END IF;",
        "END $$;",
        "-- Row Level Security on with no policies: any role other than the table owner sees nothing.",
        *[f"ALTER TABLE {SCHEMA}.{t.name} ENABLE ROW LEVEL SECURITY;" for t in Base.metadata.sorted_tables],
        "",
        "-- Recommended: run the app as its own role, and keep the audit trail append-only:",
        "--   CREATE ROLE portal_app LOGIN PASSWORD '...';  (then make it the owner of the portal schema's tables)",
        f"--   REVOKE UPDATE, DELETE ON {SCHEMA}.activity_events FROM portal_app;",
        f"--   GRANT UPDATE (actor_email, actor_name, ip, user_agent, details, redacted_at), DELETE ON {SCHEMA}.activity_events TO portal_app;",
        "",
    ]
    out = ROOT / "db" / "schema.sql"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(parts))
    print(f"Wrote {out.relative_to(ROOT)}")


DESCRIPTIONS = {
    "users": "Portal logins: admins, clients (linked to a Zoho Contact with an active deal) and guests (a Zoho Lead).",
    "consents": "What each person agreed to, when, and under which privacy policy version.",
    "otp_challenges": "One-time codes for sign-in, sign-up and password reset (hashes only; deleted after a day).",
    "activity_events": "Append-only, hash-chained audit trail. Readable by admins only.",
    "crm_agents": "Copy of Zoho CRM users (agents).",
    "crm_contacts": "Copy of Zoho Contacts (clients).",
    "crm_properties": "Copy of the Zoho Properties module (listings).",
    "crm_deal_stages": "The Deals Stage picklist, in pipeline order.",
    "crm_deals": "Copy of Zoho Deals.",
    "crm_leads": "Copy of Zoho Leads from portal sign-ups and referrals.",
    "crm_messages": "Copy of portal conversation Notes (never internal agent notes).",
    "crm_tasks": "Copy of follow-up Tasks created for agents.",
    "sync_state": "Zoho -> portal sync progress per module.",
}

GROUPS = [
    ("Portal-owned", "Held only by the portal.", ["users", "consents", "otp_challenges", "activity_events"]),
    ("CRM copy", "Synced from Zoho CRM, which stays the source of truth.",
     ["crm_agents", "crm_contacts", "crm_properties", "crm_deal_stages", "crm_deals", "crm_leads", "crm_messages", "crm_tasks", "sync_state"]),
]

# Links that are matched on Zoho ids but not enforced, because the portal and
# the CRM copy are written at different times.
LOGICAL_LINKS = [("crm_contacts", "users", "zoho_contact_id", "client login"), ("crm_leads", "users", "zoho_lead_id", "guest login")]


def _type(column) -> str:
    text = str(column.type.compile(dialect=postgresql.dialect())).lower()
    return text.replace("character varying", "varchar").replace("timestamp with time zone", "timestamptz").split("(")[0].replace(" ", "_")


def data_model(_: argparse.Namespace) -> None:
    """docs/DATA_MODEL.md: Mermaid diagram plus a data dictionary, from app/db.py."""
    tables = {t.name: t for t in Base.metadata.sorted_tables}
    lines = ["# Client Portal data model", "",
             "> Generated by `python -m app.cli data-model` from `app/db.py`. Do not edit by hand.", "",
             "Two groups of tables, all in the private `portal` schema:", ""]
    lines += [f"- **{name}**: {desc} ({len(names)} tables)" for name, desc, names in GROUPS]
    lines += ["", "Keys: every table has a primary key (`PK`). CRM-copy tables use a portal UUID `id` plus the Zoho record id "
              "`zoho_id` (unique, `UK`); references between them (`FK`) point at `zoho_id` and are checked at commit. "
              "Dotted lines in the diagram are links matched on Zoho ids but not enforced.", "",
              "## Diagram", "", "```mermaid", "erDiagram"]
    for table in tables.values():
        for fkc in table.foreign_keys:
            parent = fkc.column.table.name
            child_col = fkc.parent
            card = "o|--o{" if child_col.nullable else "||--o{"
            label = child_col.name.replace("_zoho_id", "").replace("_id", "").replace("_", " ")
            lines.append(f'    {parent} {card} {table.name} : "{label}"')
    for parent, child, col, label in LOGICAL_LINKS:
        lines.append(f'    {parent} |o..o| {child} : "{label}"')
    for table in tables.values():
        lines.append(f"    {table.name} {{")
        for c in table.columns:
            keys = ",".join(k for k, on in (("PK", c.primary_key), ("FK", bool(c.foreign_keys)), ("UK", bool(c.unique))) if on)
            lines.append(f"        {_type(c)} {c.name}{(' ' + keys) if keys else ''}")
        lines.append("    }")
    lines += ["```", "", "## Data dictionary", ""]
    for name, desc, names in GROUPS:
        lines += [f"### {name}", "", desc, ""]
        for tname in names:
            t = tables[tname]
            lines += [f"#### `{tname}`", "", DESCRIPTIONS[tname], "", "| Column | Type | Key | Null | Description / Zoho source |", "|---|---|---|---|---|"]
            for c in t.columns:
                keys = ", ".join(k for k, on in (("PK", c.primary_key), ("UK", bool(c.unique)), ("FK → " + ", ".join(f"{f.column.table.name}.{f.column.name}" for f in c.foreign_keys), bool(c.foreign_keys))) if on)
                lines.append(f"| `{c.name}` | {_type(c)} | {keys} | {'yes' if c.nullable and not c.primary_key else 'no'} | {(c.comment or '').replace('|', '/')} |")
            checks = [str(ck.sqltext) for ck in t.constraints if ck.__class__.__name__ == "CheckConstraint"]
            if checks:
                lines += ["", "Rules: " + "; ".join(f"`{ck}`" for ck in checks)]
            lines.append("")
    out = ROOT / "docs" / "DATA_MODEL.md"
    out.write_text("\n".join(lines))
    print(f"Wrote {out.relative_to(ROOT)}")


def main() -> None:
    parser = argparse.ArgumentParser(prog="python -m app.cli")
    sub = parser.add_subparsers(dest="command", required=True)
    cu = sub.add_parser("create-user")
    cu.add_argument("--email", required=True)
    cu.add_argument("--role", choices=["admin", "client"], default="client")
    cu.add_argument("--name")
    cu.add_argument("--password", help="omit to be prompted (keeps it out of shell history)")
    mc = sub.add_parser("mcp-check")
    mc.add_argument("--schemas", action="store_true")
    sub.add_parser("field-docs")
    sub.add_parser("schema-sql")
    sub.add_parser("data-model")
    args = parser.parse_args()
    if args.command == "create-user":
        asyncio.run(create_user(args))
    elif args.command == "mcp-check":
        asyncio.run(mcp_check(args))
    elif args.command == "field-docs":
        field_docs(args)
    elif args.command == "data-model":
        data_model(args)
    else:
        schema_sql(args)


if __name__ == "__main__":
    main()
