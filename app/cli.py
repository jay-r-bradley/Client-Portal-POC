"""Command-line tools:

    python -m app.cli create-user --role admin --email you@company.com --name "Your Name"
    python -m app.cli create-user --email client@example.com            (client; needs a Zoho Contact with an open deal)
    python -m app.cli mcp-check [--schemas]
    python -m app.cli field-docs        writes docs/ZOHO_FIELDS.md
    python -m app.cli schema-sql        writes db/schema.sql (PostgreSQL)
"""

from __future__ import annotations

import argparse
import asyncio
import getpass
import sys

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from .config import ROOT, load_settings
from .db import Base, Database
from .main import create_crm
from .security.passwords import password_problem
from .stores import UserStore
from .zoho.field_catalog import field_catalog


async def create_user(args: argparse.Namespace) -> None:
    settings = load_settings()
    password = args.password or getpass.getpass("Password (at least 10 characters): ")
    problem = password_problem(password, args.email)
    if problem:
        sys.exit(problem)
    db = Database(settings.database_url)
    await db.create_all()
    users = UserStore(db)
    if await users.by_email(args.email):
        sys.exit("That email already has an account.")
    if args.role == "admin":
        if not args.name:
            sys.exit("Give the admin a --name.")
        user = await users.create(email=args.email, password=password, role="admin", name=args.name, email_verified=False)
        print(f"Admin account ready: {user.email} ({user.name}). They confirm their email with a code at first sign-in.")
    else:
        crm = create_crm(settings)
        contact = await crm.find_contact_by_email(args.email)
        if not contact:
            sys.exit(f"No Zoho Contact found for {args.email}.")
        won, lost = settings.crm.won_stages, settings.crm.lost_stages
        if not any(d["stage"] not in won and d["stage"] not in lost for d in await crm.list_deals(contact["id"])):
            sys.exit(f"{contact['name']} has no active deal in Zoho; client access needs one.")
        user = await users.create(email=args.email, password=password, role="client", name=contact["name"], contact_id=contact["id"],
                                  must_change_password=True)
        print(f"Client access granted: {user.email} -> Zoho Contact {contact['id']} ({contact['name']}).")
    await db.dispose()


async def mcp_check(args: argparse.Namespace) -> None:
    from .mcp_zoho.connection import McpConnection
    from .mcp_zoho.zoho_mcp_api import ZohoMcpApi, load_tool_map

    settings = load_settings()
    if not settings.zoho_mcp.url:
        sys.exit("Set ZOHO_MCP_URL in .env first (Zoho CRM > Setup > Developer Hub > MCP for AI Agents).")
    headers = {"Authorization": settings.zoho_mcp.authorization} if settings.zoho_mcp.authorization else {}
    connection = McpConnection(settings.zoho_mcp.url, headers=headers)
    try:
        tools = await connection.list_tools()
        print(f"Connected. The server offers {len(tools)} tools:\n")
        for tool in tools:
            print(f"- {tool.name}: {(tool.description or '').splitlines()[0][:100] if tool.description else ''}")
            if args.schemas:
                import json
                print("    " + json.dumps(tool.input_schema if hasattr(tool, "input_schema") else tool.inputSchema, indent=2).replace("\n", "\n    "))
        tool_map = load_tool_map(settings.zoho_mcp.tool_map_path)
        names = {t.name for t in tools}
        print(f"\nMapping in {settings.zoho_mcp.tool_map_path}:")
        for op, entry in tool_map.items():
            found = entry["tool"] in names
            print(f"  {'OK     ' if found else 'MISSING'} {op} -> {entry['tool']}")
            if op == "coql" and not found:
                sys.exit('The required "coql" tool was not found. Edit the mapping file with the right tool name and arguments.')
        api = ZohoMcpApi(connection=connection, tool_map=tool_map, crm=settings.crm)
        d = settings.crm.deal
        rows = await api.coql(f"select {d.name}, {d.stage} from {settings.crm.deals_module} where {d.stage} is not null limit 1")
        print(f"\nTest COQL query returned {len(rows)} deal row(s). The AI can read Zoho CRM over MCP.")
    finally:
        await connection.close()


def field_docs(_: argparse.Namespace) -> None:
    settings = load_settings()
    catalog = field_catalog(settings)
    to_create = [(m["label"], f) for m in catalog for f in m["fields"] if not f["standard"]]
    other = [(label, f) for label, f in to_create if label != "Properties"]
    cell = lambda t: str(t).replace("|", "\\|")  # noqa: E731
    lines = [
        "# Zoho CRM fields used by the Client Portal", "",
        "> Generated by `python -m app.cli field-docs` from `app/zoho/field_catalog.py`. Do not edit by hand.",
        "> The same list, with a live found/missing check against your org, is in the admin console under **Zoho setup**.", "",
        "API names below are the defaults. If your org already uses different names, keep your fields and set the matching",
        "`CRM_*` variable in `.env` (see `app/config.py`).", "",
        "## Checklist: what to create in Zoho", "",
        f"1. **Custom module `{settings.crm.properties_module}`** with the fields marked *Create* below.",
        *[f"{i + 2}. **{label}: `{f['apiName']}`** ({f['label']}, {f['type']})." for i, (label, f) in enumerate(other)],
        f"{len(other) + 2}. **Leads: Lead Source picklist values `{settings.crm.signup.lead_source}` and `{settings.crm.referral.lead_source}`**.",
        f"{len(other) + 3}. **{settings.crm.properties_module}: Status picklist value `{settings.crm.available_status}`** for listings clients may see.", "",
        f"Everything else is a standard Zoho field. In total: {sum(len(m['fields']) for m in catalog)} fields across {len(catalog)} modules, {len(to_create)} to create.", "",
    ]
    for m in catalog:
        lines += [f"## {m['label']} (`{m['module']}`): {m['kind']}", "", m["purpose"], ""]
        if m["fields"]:
            lines += ["| Field label | API name | Type | Required | Create? | Used for |", "|---|---|---|---|---|---|"]
            lines += [f"| {cell(f['label'])} | `{f['apiName']}` | {cell(f['type'])} | {'Yes' if f['required'] else 'Optional'} | "
                      f"{'Standard' if f['standard'] else '**Create**'} | {cell(f['purpose'])} |" for f in m["fields"]]
            lines.append("")
    lines += ["## OAuth scopes", "", "`ZohoCRM.modules.ALL, ZohoCRM.coql.READ, ZohoCRM.settings.fields.READ, ZohoCRM.users.READ`", "",
              "For least privilege, narrow `modules.ALL` to: read on Contacts, Deals and Properties; create and update on Leads; create on Notes and Tasks.", ""]
    out = ROOT / "docs" / "ZOHO_FIELDS.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"Wrote {out.relative_to(ROOT)}")


def schema_sql(_: argparse.Namespace) -> None:
    dialect = postgresql.dialect()
    parts = ["-- Client Portal database schema (PostgreSQL 16+).",
             "-- Generated by `python -m app.cli schema-sql` from app/db.py. The app also creates these tables on first start.", ""]
    for table in Base.metadata.sorted_tables:
        parts.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";\n")
        for index in sorted(table.indexes, key=lambda i: i.name):
            parts.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";")
        parts.append("")
    parts += [
        "-- The audit trail is append-only. Run the app as a role that cannot UPDATE or DELETE it",
        "-- except through the erasure and retention jobs, e.g.:",
        "--   REVOKE UPDATE, DELETE ON activity_events FROM portal_app;",
        "--   GRANT UPDATE (actor_email, actor_name, ip, user_agent, details, redacted_at), DELETE ON activity_events TO portal_app;",
        "",
    ]
    out = ROOT / "db" / "schema.sql"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(parts))
    print(f"Wrote {out.relative_to(ROOT)}")


def main() -> None:
    parser = argparse.ArgumentParser(prog="python -m app.cli")
    sub = parser.add_subparsers(dest="command", required=True)
    cu = sub.add_parser("create-user")
    cu.add_argument("--email", required=True)
    cu.add_argument("--role", choices=["admin", "client"], default="client")
    cu.add_argument("--name")
    cu.add_argument("--password", help="omit to be prompted (keeps it out of shell history)")
    mc = sub.add_parser("mcp-check")
    mc.add_argument("--schemas", action="store_true")
    sub.add_parser("field-docs")
    sub.add_parser("schema-sql")
    args = parser.parse_args()
    if args.command == "create-user":
        asyncio.run(create_user(args))
    elif args.command == "mcp-check":
        asyncio.run(mcp_check(args))
    elif args.command == "field-docs":
        field_docs(args)
    else:
        schema_sql(args)


if __name__ == "__main__":
    main()
